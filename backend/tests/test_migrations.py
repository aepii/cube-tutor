"""The Alembic history is the schema of record.

`_schema` (conftest) already built the test DB with `alembic upgrade head`, so
every other test runs on the migrated schema. These tests pin the rest: the
migrations match the models, and the history can be walked down and back up.
"""

from alembic import command
from sqlalchemy import inspect
from sqlmodel import SQLModel

from app.core.db import engine
from tests.conftest import alembic_config

APP_TABLES = {t.name for t in SQLModel.metadata.sorted_tables}


def _tables() -> set[str]:
    return set(inspect(engine).get_table_names())


def test_migrations_create_every_model_table():
    assert APP_TABLES <= _tables()
    assert "alembic_version" in _tables()


def test_models_match_migrations():
    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_config())


def test_downgrade_then_upgrade():
    cfg = alembic_config()
    command.downgrade(cfg, "base")
    assert not APP_TABLES & _tables()
    command.upgrade(cfg, "head")
    assert APP_TABLES <= _tables()
